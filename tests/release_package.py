#!/usr/bin/env python3
"""Validate release archive contents, identities, permissions and checksums."""
import argparse
import hashlib
import importlib.util
import json
import os
from pathlib import Path
import subprocess
import tarfile
import tempfile
import unittest

ROOT = Path(__file__).resolve().parents[1]
spec = importlib.util.spec_from_file_location('package_release', ROOT / 'scripts/package_release.py')
release = importlib.util.module_from_spec(spec)
spec.loader.exec_module(release)


def beta_args(**overrides):
    values = dict(tag=None, beta=True, sequence=42, attempt=1, source_sha='a' * 40)
    values.update(overrides)
    return argparse.Namespace(**values)


class ReleaseArchive(unittest.TestCase):
    def test_mismatched_or_unsafe_versions_are_refused(self):
        for tag, version in [('v0.2.0', '0.3.0'), ('0.3.0', '0.3.0'), ('v../../x', '../../x')]:
            with self.assertRaises(ValueError):
                release.validate_tag(tag, version)
        release.validate_tag('v0.3.0', '0.3.0')

    def test_archive_contains_only_installable_binary_and_public_docs(self):
        with tempfile.TemporaryDirectory() as tmp:
            root = Path(tmp)
            binary = root / 'kiro-agents'
            binary.write_bytes(b'test native binary')
            for name in ['LICENSE', 'README.md', 'CHANGELOG.md', 'private.log']:
                (root / name).write_text(name)
            archive = release.create_archive(root, binary, '0.3.0', root / 'out')
            prefix = 'kiro-agents-v0.3.0-x86_64-unknown-linux-gnu/'
            with tarfile.open(archive) as tar:
                self.assertEqual(tar.getnames(), [prefix + n for n in ['kiro-agents', 'LICENSE', 'README.md', 'CHANGELOG.md']])
                self.assertEqual(tar.getmember(prefix + 'kiro-agents').mode, 0o755)
                self.assertEqual(tar.extractfile(prefix + 'kiro-agents').read(), binary.read_bytes())
            self.assertEqual((root / 'out/SHA256SUMS').read_text(), hashlib.sha256(archive.read_bytes()).hexdigest() + '  ' + archive.name + '\n')
            first = archive.read_bytes()
            release.create_archive(root, binary, '0.3.0', root / 'out')
            self.assertEqual(first, archive.read_bytes())

    def test_beta_version_is_next_patch_with_run_identity(self):
        self.assertEqual(release.beta_version('0.3.0', 42, 1), '0.3.1-beta.42.1')
        self.assertEqual(release.beta_version('0.0.0', 1, 1), '0.0.1-beta.1.1')
        self.assertEqual(release.beta_version('1.2.9', 7, 3), '1.2.10-beta.7.3')
        release.validate_tag('v' + release.beta_version('0.3.0', 42, 1), release.beta_version('0.3.0', 42, 1))

    def test_prerelease_sources_and_bad_run_numbers_are_refused(self):
        for source in ['0.3.1-beta.42.1', '0.3.0-rc.1', '0.3.0+build.7', '0.3', '0.3.0.1']:
            with self.assertRaises(ValueError):
                release.beta_version(source, 42, 1)
        for sequence, attempt in [(0, 1), (-1, 1), (1, 0), (1, -3)]:
            with self.assertRaises(ValueError):
                release.beta_version('0.3.0', sequence, attempt)

    def test_beta_and_stable_argument_combinations(self):
        release.validate_arguments(beta_args())
        release.validate_arguments(argparse.Namespace(tag='v0.3.0', beta=False, sequence=None, attempt=None, source_sha=None))
        for bad in [beta_args(sequence=None), beta_args(attempt=None), beta_args(source_sha=None),
                    beta_args(source_sha='abc'), beta_args(source_sha='A' * 40), beta_args(tag='v0.3.1-beta.42.1'),
                    argparse.Namespace(tag=None, beta=False, sequence=None, attempt=None, source_sha=None),
                    argparse.Namespace(tag='v0.3.0', beta=False, sequence=42, attempt=1, source_sha=None),
                    argparse.Namespace(tag='v0.3.0', beta=False, sequence=None, attempt=None, source_sha='a' * 40)]:
            with self.assertRaises(ValueError):
                release.validate_arguments(bad)

    def write_manifests(self, root):
        (root / 'Cargo.toml').write_text(
            '[package]\nname = "kiro-agents"\nversion = "0.3.0"\nedition = "2021"\n\n'
            '[dependencies]\nanyhow = "1"\nclap = { version = "4", features = ["derive"] }\n\n'
            '[dependencies.tempfile]\nversion = "3"\n')
        (root / 'Cargo.lock').write_text(
            '# This file is automatically @generated by Cargo.\n'
            '# It is not intended for manual editing.\nversion = 4\n\n'
            '[[package]]\nname = "anyhow"\nversion = "1.0.90"\nsource = "registry+https://github.com/rust-lang/crates.io-index"\n\n'
            '[[package]]\nname = "kiro-agents"\nversion = "0.3.0"\n\n'
            '[[package]]\nname = "tempfile"\nversion = "3.13.0"\n')

    def test_stamping_changes_only_root_package_versions(self):
        with tempfile.TemporaryDirectory() as tmp:
            root = Path(tmp)
            self.write_manifests(root)
            release.stamp_versions(root, '0.3.1-beta.42.1', 'kiro-agents')
            manifest = (root / 'Cargo.toml').read_text()
            self.assertIn('version = "0.3.1-beta.42.1"', manifest)
            self.assertIn('anyhow = "1"', manifest)
            self.assertIn('clap = { version = "4", features = ["derive"] }', manifest)
            self.assertIn('[dependencies.tempfile]\nversion = "3"', manifest)
            lock = (root / 'Cargo.lock').read_text()
            self.assertIn('[[package]]\nname = "kiro-agents"\nversion = "0.3.1-beta.42.1"', lock)
            self.assertIn('name = "anyhow"\nversion = "1.0.90"', lock)
            self.assertIn('name = "tempfile"\nversion = "3.13.0"', lock)
            self.assertIn('version = 4', lock)

    def test_stamping_refuses_ambiguous_or_missing_root_entries(self):
        with tempfile.TemporaryDirectory() as tmp:
            root = Path(tmp)
            self.write_manifests(root)
            (root / 'Cargo.lock').write_text(
                (root / 'Cargo.lock').read_text()
                + '[[package]]\nname = "kiro-agents"\nversion = "0.2.0"\n')
            with self.assertRaises(ValueError):
                release.stamp_versions(root, '0.3.1-beta.42.1', 'kiro-agents')
            self.assertIn('name = "kiro-agents"\nversion = "0.3.0"', (root / 'Cargo.lock').read_text())
            with tempfile.TemporaryDirectory() as other:
                other_root = Path(other)
                self.write_manifests(other_root)
                (other_root / 'Cargo.lock').write_text('version = 4\n')
                with self.assertRaises(ValueError):
                    release.stamp_versions(other_root, '0.3.1-beta.42.1', 'kiro-agents')
            with self.assertRaises(ValueError):
                release.stamp_versions(root, '0.3.1-beta.42.1/', 'kiro-agents')

    def test_git_prechecks_gate_beta_builds(self):
        env = dict(os.environ, GIT_CONFIG_GLOBAL='/dev/null', GIT_CONFIG_SYSTEM='/dev/null',
                   GIT_AUTHOR_NAME='test', GIT_AUTHOR_EMAIL='test@example.com',
                   GIT_COMMITTER_NAME='test', GIT_COMMITTER_EMAIL='test@example.com')

        def git(root, *args):
            return subprocess.check_output(['git', *args], cwd=str(root), env=env, text=True).strip()

        with tempfile.TemporaryDirectory() as tmp:
            root = Path(tmp)
            git(root, 'init', '-q', '--initial-branch=main')
            (root / 'Cargo.toml').write_text('[package]\nname = "kiro-agents"\nversion = "0.3.0"\n')
            git(root, 'add', 'Cargo.toml')
            git(root, 'commit', '-q', '-m', 'init')
            sha = git(root, 'rev-parse', 'HEAD')
            release.require_clean_tracked_tree(root)
            release.require_source_sha(root, sha)
            (root / 'Cargo.toml').write_text('[package]\nname = "kiro-agents"\nversion = "0.4.0"\n')
            with self.assertRaises(ValueError):
                release.require_clean_tracked_tree(root)
            (root / 'untracked.log').write_text('ignored')
            git(root, 'add', 'Cargo.toml')
            git(root, 'commit', '-q', '-m', 'bump')
            release.require_clean_tracked_tree(root)
            self.assertNotEqual(git(root, 'rev-parse', 'HEAD'), sha)
            with self.assertRaises(ValueError):
                release.require_source_sha(root, sha)
            for bad in ['' , 'abc', 'A' * 40, 'z' * 40]:
                with self.assertRaises(ValueError):
                    release.require_source_sha(root, bad)

    def test_beta_metadata_has_exact_identity_fields(self):
        with tempfile.TemporaryDirectory() as tmp:
            out = Path(tmp)
            version = release.beta_version('0.3.0', 42, 1)
            archive = out / f'kiro-agents-v{version}-{release.TARGET}.tar.gz'
            archive.write_bytes(b'archive')
            release.write_beta_metadata(out, version, 'v' + version, 'a' * 40, archive)
            metadata = json.loads((out / 'beta.json').read_text())
            self.assertEqual(set(metadata), {'version', 'tag', 'sha', 'archive'})
            self.assertEqual(metadata, {'version': '0.3.1-beta.42.1', 'tag': 'v0.3.1-beta.42.1',
                                        'sha': 'a' * 40, 'archive': f'kiro-agents-v0.3.1-beta.42.1-{release.TARGET}.tar.gz'})

    def test_beta_archives_use_the_same_layout_as_stable(self):
        with tempfile.TemporaryDirectory() as tmp:
            root = Path(tmp)
            binary = root / 'kiro-agents'
            binary.write_bytes(b'beta native binary')
            for name in ['LICENSE', 'README.md', 'CHANGELOG.md']:
                (root / name).write_text(name)
            version = release.beta_version('0.3.0', 42, 1)
            archive = release.create_archive(root, binary, version, root / 'out')
            self.assertEqual(archive.name, f'kiro-agents-v{version}-{release.TARGET}.tar.gz')
            prefix = archive.name[:-len('.tar.gz')] + '/'
            with tarfile.open(archive) as tar:
                self.assertEqual(tar.getnames(), [prefix + n for n in ['kiro-agents', 'LICENSE', 'README.md', 'CHANGELOG.md']])
            self.assertEqual((root / 'out/SHA256SUMS').read_text(), hashlib.sha256(archive.read_bytes()).hexdigest() + '  ' + archive.name + '\n')


if __name__ == '__main__':
    unittest.main()
